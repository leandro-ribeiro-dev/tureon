import 'dart:convert';
import 'dart:typed_data';

import 'package:tureon/core/protocol/system_event_type.dart';
import 'package:tureon/core/protocol/system_message.dart';
import 'package:tureon/core/storage/message_records.dart';
import 'package:tureon/features/chats/domain/chat_message.dart' as domain;
import 'package:tureon/generated/proto/tureon.pb.dart' as pb;

/// Data mapper converting Protobuf transport messages into domain models.
abstract class ChatMessageMapper {
  static domain.ChatMessageType messageTypeFromProto(pb.MessageType type) =>
      switch (type) {
        pb.MessageType.MESSAGE_TYPE_TEXT => domain.ChatMessageType.text,
        pb.MessageType.MESSAGE_TYPE_IMAGE => domain.ChatMessageType.image,
        pb.MessageType.MESSAGE_TYPE_VIDEO => domain.ChatMessageType.video,
        pb.MessageType.MESSAGE_TYPE_AUDIO => domain.ChatMessageType.audio,
        pb.MessageType.MESSAGE_TYPE_VOICE_NOTE =>
          domain.ChatMessageType.voiceNote,
        pb.MessageType.MESSAGE_TYPE_FILE => domain.ChatMessageType.file,
        pb.MessageType.MESSAGE_TYPE_STICKER => domain.ChatMessageType.sticker,
        pb.MessageType.MESSAGE_TYPE_GIF => domain.ChatMessageType.gif,
        pb.MessageType.MESSAGE_TYPE_LOCATION => domain.ChatMessageType.location,
        pb.MessageType.MESSAGE_TYPE_CONTACT_CARD =>
          domain.ChatMessageType.contactCard,
        pb.MessageType.MESSAGE_TYPE_REPLY => domain.ChatMessageType.reply,
        pb.MessageType.MESSAGE_TYPE_FORWARD => domain.ChatMessageType.forward,
        pb.MessageType.MESSAGE_TYPE_REACTION => domain.ChatMessageType.reaction,
        pb.MessageType.MESSAGE_TYPE_EDIT => domain.ChatMessageType.edit,
        pb.MessageType.MESSAGE_TYPE_DELETE => domain.ChatMessageType.delete,
        pb.MessageType.MESSAGE_TYPE_SYSTEM => domain.ChatMessageType.system,
        _ => domain.ChatMessageType.unspecified,
      };

  static pb.MessageType messageTypeToProto(int localTypeOrdinal) =>
      switch (localTypeOrdinal) {
        1 => pb.MessageType.MESSAGE_TYPE_TEXT,
        2 => pb.MessageType.MESSAGE_TYPE_IMAGE,
        3 => pb.MessageType.MESSAGE_TYPE_VIDEO,
        4 => pb.MessageType.MESSAGE_TYPE_AUDIO,
        5 => pb.MessageType.MESSAGE_TYPE_SYSTEM,
        6 => pb.MessageType.MESSAGE_TYPE_VOICE_NOTE,
        7 => pb.MessageType.MESSAGE_TYPE_FILE,
        8 => pb.MessageType.MESSAGE_TYPE_STICKER,
        9 => pb.MessageType.MESSAGE_TYPE_GIF,
        10 => pb.MessageType.MESSAGE_TYPE_LOCATION,
        11 => pb.MessageType.MESSAGE_TYPE_CONTACT_CARD,
        12 => pb.MessageType.MESSAGE_TYPE_REPLY,
        13 => pb.MessageType.MESSAGE_TYPE_FORWARD,
        14 => pb.MessageType.MESSAGE_TYPE_REACTION,
        15 => pb.MessageType.MESSAGE_TYPE_EDIT,
        16 => pb.MessageType.MESSAGE_TYPE_DELETE,
        _ => pb.MessageType.MESSAGE_TYPE_UNSPECIFIED,
      };

  static int messageTypeWireValue(domain.ChatMessageType type) =>
      messageTypeToProto(type.index).value;

  static DecodedChatPayload decodePayload(
    domain.ChatMessageType type,
    List<int> payload,
  ) {
    final fallback = utf8.decode(payload, allowMalformed: true);
    if (type == domain.ChatMessageType.text ||
        type == domain.ChatMessageType.unspecified ||
        type == domain.ChatMessageType.system) {
      return DecodedChatPayload(body: fallback);
    }
    try {
      final decoded = jsonDecode(fallback);
      if (decoded is! Map<String, Object?> || decoded['version'] != 1) {
        return DecodedChatPayload(body: fallback);
      }
      final rawAttachment = decoded['attachment'];
      domain.ChatAttachment? attachment;
      if (rawAttachment is Map<String, Object?>) {
        // Never trust a peer-supplied local path. Paths are only generated by
        // this installation and remain outside the message wire format.
        final safeAttachment = Map<String, Object?>.from(rawAttachment)
          ..remove('local_path');
        attachment = domain.ChatAttachment.fromJson(safeAttachment);
      }
      return DecodedChatPayload(
        body: decoded['caption'] as String? ?? decoded['text'] as String? ?? '',
        replyToMessageId: decoded['reply_to_message_id'] as String?,
        attachment: attachment,
      );
    } on FormatException {
      return DecodedChatPayload(body: fallback);
    } on TypeError {
      return DecodedChatPayload(body: fallback);
    }
  }

  static Uint8List replyPayload(String text, String replyToMessageId) =>
      Uint8List.fromList(
        utf8.encode(
          jsonEncode({
            'version': 1,
            'caption': text,
            'reply_to_message_id': replyToMessageId,
          }),
        ),
      );

  static Uint8List attachmentDraftPayload({
    required String caption,
    required domain.ChatAttachment attachment,
    String? replyToMessageId,
  }) => Uint8List.fromList(
    utf8.encode(
      jsonEncode({
        'version': 1,
        'draft': true,
        'caption': caption,
        ...?_replyField(replyToMessageId),
        'attachment': attachment.toJson(),
      }),
    ),
  );

  static Uint8List attachmentPayload({
    required String caption,
    required domain.ChatAttachment attachment,
    String? replyToMessageId,
  }) => Uint8List.fromList(
    utf8.encode(
      jsonEncode({
        'version': 1,
        'caption': caption,
        ...?_replyField(replyToMessageId),
        'attachment': attachment.toJson(includeLocalPath: false),
      }),
    ),
  );

  static Map<String, Object?>? _replyField(String? replyToMessageId) =>
      replyToMessageId == null
      ? null
      : {'reply_to_message_id': replyToMessageId};

  static DateTime createdAtFromDelivery(pb.MessageDelivery delivery) {
    final micros = delivery.createdAtMicros.toInt();
    if (micros > 0) {
      return DateTime.fromMicrosecondsSinceEpoch(micros, isUtc: true);
    }
    return DateTime.fromMillisecondsSinceEpoch(
      delivery.createdAt.toInt() * 1000,
      isUtc: true,
    );
  }

  static SystemEventType systemEventTypeFromProto(pb.SystemEventType type) =>
      switch (type) {
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_JOINED_GROUP =>
          SystemEventType.userJoinedGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_LEFT_GROUP =>
          SystemEventType.userLeftGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_ADDED_TO_GROUP =>
          SystemEventType.userAddedToGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_REMOVED_FROM_GROUP =>
          SystemEventType.userRemovedFromGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_BANNED_FROM_GROUP =>
          SystemEventType.userBannedFromGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_UNBANNED_FROM_GROUP =>
          SystemEventType.userUnbannedFromGroup,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_GROUP_CREATED =>
          SystemEventType.groupCreated,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_GROUP_RENAMED =>
          SystemEventType.groupRenamed,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_GROUP_AVATAR_CHANGED =>
          SystemEventType.groupAvatarChanged,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_GROUP_UPDATED =>
          SystemEventType.groupUpdated,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_JOINED_CHANNEL =>
          SystemEventType.userJoinedChannel,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_LEFT_CHANNEL =>
          SystemEventType.userLeftChannel,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_ADDED_TO_CHANNEL =>
          SystemEventType.userAddedToChannel,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_REMOVED_FROM_CHANNEL =>
          SystemEventType.userRemovedFromChannel,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_BANNED_FROM_CHANNEL =>
          SystemEventType.userBannedFromChannel,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_ROLE_CHANGED =>
          SystemEventType.userRoleChanged,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_CHANNEL_CREATED =>
          SystemEventType.channelCreated,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_CHANNEL_RENAMED =>
          SystemEventType.channelRenamed,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_CHANNEL_UPDATED =>
          SystemEventType.channelUpdated,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_GROUP_POLICY_CHANGED =>
          SystemEventType.groupPolicyChanged,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_CHANNEL_POLICY_CHANGED =>
          SystemEventType.channelPolicyChanged,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_CHANNEL_BROADCAST =>
          SystemEventType.channelBroadcast,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_MUTED =>
          SystemEventType.userMuted,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_USER_UNMUTED =>
          SystemEventType.userUnmuted,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_BOT_ADDED =>
          SystemEventType.botAdded,
        pb.SystemEventType.SYSTEM_EVENT_TYPE_BOT_REMOVED =>
          SystemEventType.botRemoved,
        _ => SystemEventType.unspecified,
      };

  static SystemMessage systemMessageFromProto(
    pb.SystemMessage proto,
  ) => SystemMessage(
    eventType: systemEventTypeFromProto(proto.eventType),
    actorUserId: proto.actorUserId,
    actorUsername: proto.metadata['actor_username'],
    targetUserId: proto.targetUserId.isEmpty ? null : proto.targetUserId,
    targetUsername: proto.metadata['target_username'],
    groupId: proto.groupId.isEmpty ? null : proto.groupId,
    channelId: proto.channelId.isEmpty ? null : proto.channelId,
    reason: proto.reason.isEmpty ? null : proto.reason,
    metadataJson: proto.metadata.isEmpty ? null : jsonEncode(proto.metadata),
    role: proto.metadata['role'],
    changedFields: (proto.metadata['changed_fields'] ?? '')
        .split(',')
        .map((field) => field.trim())
        .where((field) => field.isNotEmpty)
        .toList(growable: false),
    membersCanSendMessages: _parseBoolean(
      proto.metadata['members_can_send_messages'],
    ),
    slowModeSeconds: int.tryParse(proto.metadata['slow_mode_seconds'] ?? ''),
    permissionValues: _permissionValues(proto.metadata),
    timestamp: DateTime.fromMillisecondsSinceEpoch(
      proto.timestamp.toInt() * 1000,
      isUtc: true,
    ),
  );

  static Map<String, bool> _permissionValues(Map<String, String> metadata) {
    const keys = <String>[
      'members_can_send_messages',
      'members_can_send_media',
      'members_can_send_stickers_gifs',
      'members_can_embed_links',
      'members_can_add_members',
      'members_can_change_info',
      'members_can_react',
      'members_can_forward',
    ];
    final result = <String, bool>{};
    for (final key in keys) {
      final value = _parseBoolean(metadata[key]);
      if (value != null) result[key] = value;
    }
    return Map<String, bool>.unmodifiable(result);
  }

  static bool? _parseBoolean(String? value) => switch (value?.toLowerCase()) {
    'true' => true,
    'false' => false,
    _ => null,
  };

  static pb.SendMessageRequest outboxToSendMessageRequest(
    OutboxRecord outbox, {
    List<int>? payload,
  }) {
    return pb.SendMessageRequest(
      messageId: outbox.messageId,
      chatId: outbox.chatId,
      senderRecipientId: outbox.senderRecipientId,
      senderDeviceId: outbox.senderDeviceId,
      targetRecipientId: outbox.targetRecipientId,
      targetDeviceId: outbox.targetDeviceId ?? '',
      chatKind: outbox.isSecret
          ? pb.ChatKind.CHAT_KIND_SECRET
          : pb.ChatKind.CHAT_KIND_NORMAL,
      messageType: messageTypeToProto(outbox.messageType),
      payload: Uint8List.fromList(payload ?? outbox.payload),
    );
  }
}

class DecodedChatPayload {
  const DecodedChatPayload({
    this.body = '',
    this.replyToMessageId,
    this.attachment,
  });

  final String body;
  final String? replyToMessageId;
  final domain.ChatAttachment? attachment;
}
